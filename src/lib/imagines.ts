/** バトルイマジンのスキルなら親のID（39xx）。派生（39xxyy）もまとめる */
export function imagineBaseId(skillId: number): number | null {
  if (skillId >= 3900 && skillId <= 3999) return skillId;
  if (skillId >= 390000 && skillId <= 399999) return Math.floor(skillId / 100);
  return null;
}

/** イマジン名。この表に無ければスキル名の表、それも無ければ「イマジン 3969」 */
export function imagineName(skillId: number, skillNames?: Record<string, string> | null): string | null {
  const base = imagineBaseId(skillId);
  if (base === null) return null;
  return IMAGINE_NAMES[base] ?? skillNames?.[String(base)] ?? `イマジン ${base}`;
}
